%% =========================================================
% Read data
% =========================================================

X1 = readmatrix('HCP_5.csv');
X2 = readmatrix('HCP_7.csv');
X3 = readmatrix('HCP_10.csv');


%% =========================================================
% Remove completely empty rows and columns, if present
% =========================================================

X1(all(isnan(X1),2), :) = [];
X2(all(isnan(X2),2), :) = [];
X3(all(isnan(X3),2), :) = [];

X1(:, all(isnan(X1),1)) = [];
X2(:, all(isnan(X2),1)) = [];
X3(:, all(isnan(X3),1)) = [];


%% =========================================================
% Check sizes
% =========================================================

fprintf('X1: %d x %d\n', size(X1,1), size(X1,2));
fprintf('X2: %d x %d\n', size(X2,1), size(X2,2));
fprintf('X3: %d x %d\n', size(X3,1), size(X3,2));


%% =========================================================
% Matrix dimensions
% =========================================================

n1 = size(X1,2);
n2 = size(X2,2);
n3 = size(X3,2);


%% =========================================================
% Average selected columns
%
% K = 5  : X1(:,4)
% K = 7  : X2(:,6)
% K = 10 : X3(:,9)
% =========================================================

X_avg = mean( ...
    [X1(:,4), X2(:,6), X3(:,9)], ...
    2, ...
    'omitnan' ...
);


%% =========================================================
% Combine matrices
% =========================================================

X = [ ...
    X1, ...
    X2, ...
    X3, ...
    X_avg ...
];

[nRows, nCols] = size(X);


%% =========================================================
% X-axis labels
% Last column has no bottom label
% =========================================================

x_labs = [ ...
    string(2:(n1 + 1)), ...
    string(2:(n2 + 1)), ...
    string(2:(n3 + 1)), ...
    "" ...
];


%% =========================================================
% Y-axis labels
% =========================================================

metric_names = { ...
    'Silhouette Index', ...
    'Hamming Distance', ...
    'NMI', ...
    'VI Distance', ...
    'Modularity', ...
    'Dunn', ...
    'CH Index', ...
    'C Index', ...
    'zRand' ...
};

y_labs = [ ...
    {'Loglikelihood'}, ...
    repmat(metric_names, 1, 3) ...
];


%% =========================================================
% Font sizes
% =========================================================

fontX      = 25;
fontY      = 22;
fontTop    = 24;
fontTopAvg = 18;
fontCB     = 20;


%% =========================================================
% Create wider figure
% =========================================================

figure( ...
    'Color', 'w', ...
    'Position', [50 100 2200 720] ...
);


%% =========================================================
% Main heatmap
%
% Wider heatmap using more horizontal space
% =========================================================

axHeat = axes( ...
    'Position', [0.18 0.12 0.76 0.72] ...
);

h = imagesc(axHeat, X);

% Put first row at top
set(axHeat, 'YDir', 'reverse');


%% =========================================================
% Make NaN entries white
% =========================================================

set(h, ...
    'AlphaData', ~isnan(X) ...
);

axHeat.Color = 'white';


%% =========================================================
% Colormap: light blue -> dark blue
% =========================================================

nColors = 256;

lightBlue = [0.68 0.85 0.90];
darkBlue  = [0.00 0.00 0.55];

cmap = [ ...
    linspace(lightBlue(1), darkBlue(1), nColors)', ...
    linspace(lightBlue(2), darkBlue(2), nColors)', ...
    linspace(lightBlue(3), darkBlue(3), nColors)' ...
];

colormap(axHeat, cmap);


%% =========================================================
% Color scale
% =========================================================

clim(axHeat, [0 100]);


%% =========================================================
% Colorbar
% =========================================================

cb = colorbar(axHeat);

cb.Label.String = 'Percentage';
cb.Label.FontSize = fontCB;
cb.FontSize = fontCB;


%% =========================================================
% Axis labels and ticks
% =========================================================

axHeat.XTick = 1:nCols;
axHeat.XTickLabel = x_labs;
axHeat.XTickLabelRotation = 0;

axHeat.YTick = 1:nRows;
axHeat.YTickLabel = y_labs;

axHeat.XAxis.FontSize = fontX;
axHeat.YAxis.FontSize = fontY;

axHeat.TickLength = [0 0];

xlim(axHeat, [0.5 nCols + 0.5]);
ylim(axHeat, [0.5 nRows + 0.5]);

box(axHeat, 'on');

hold(axHeat, 'on');


%% =========================================================
% White cell borders
% =========================================================

for xx = 1.5:1:(nCols - 0.5)

    xline(axHeat, ...
        xx, ...
        'Color', 'white', ...
        'LineWidth', 0.35 ...
    );

end


for yy = 1.5:1:(nRows - 0.5)

    yline(axHeat, ...
        yy, ...
        'Color', 'white', ...
        'LineWidth', 0.35 ...
    );

end


%% =========================================================
% Black vertical separators between K groups
% =========================================================

% K = 5 / K = 7
xline(axHeat, ...
    n1 + 0.5, ...
    'Color', 'black', ...
    'LineWidth', 1.5 ...
);

% K = 7 / K = 10
xline(axHeat, ...
    n1 + n2 + 0.5, ...
    'Color', 'black', ...
    'LineWidth', 1.5 ...
);

% No black separator between K = 10 and Avg


%% =========================================================
% Dashed horizontal separators
% =========================================================

yline(axHeat, ...
    10.5, ...
    '--', ...
    'Color', [0.35 0.35 0.35], ...
    'LineWidth', 1.2 ...
);

yline(axHeat, ...
    19.5, ...
    '--', ...
    'Color', [0.35 0.35 0.35], ...
    'LineWidth', 1.2 ...
);


%% =========================================================
% Red boundaries around selected columns
%
% X1(:,4)
% X2(:,6)
% X3(:,9)
% Avg
% =========================================================

col_K5  = 4;
col_K7  = n1 + 6;
col_K10 = n1 + n2 + 9;
col_Avg = nCols;

highlightCols = [ ...
    col_K5, ...
    col_K7, ...
    col_K10, ...
    col_Avg ...
];

for c = highlightCols

    rectangle(axHeat, ...
        'Position', [ ...
            c - 0.5, ...
            0.5, ...
            1, ...
            nRows ...
        ], ...
        'EdgeColor', 'red', ...
        'LineWidth', 3.5, ...
        'LineStyle', '-' ...
    );

end

hold(axHeat, 'off');


%% =========================================================
% Get true heatmap position after colorbar adjustment
% =========================================================

drawnow;

heatPos = axHeat.Position;


%% =========================================================
% Top colored annotation strip
% =========================================================

axTop = axes( ...
    'Position', [ ...
        heatPos(1), ...
        heatPos(2) + heatPos(4) + 0.015, ...
        heatPos(3), ...
        0.055 ...
    ] ...
);

hold(axTop, 'on');


%% =========================================================
% Group colors
% =========================================================

groupColors = [ ...
    0.0000 0.4470 0.7410; ...   % K = 5
    0.8500 0.3250 0.0980; ...   % K = 7
    0.9290 0.6940 0.1250; ...   % K = 10
    0.7000 0.7000 0.7000  ...   % Avg
];


%% =========================================================
% K = 5 block
% =========================================================

patch(axTop, ...
    [ ...
        0.5, ...
        n1 + 0.5, ...
        n1 + 0.5, ...
        0.5 ...
    ], ...
    [0, 0, 1, 1], ...
    groupColors(1,:), ...
    'EdgeColor', 'none' ...
);


%% =========================================================
% K = 7 block
% =========================================================

patch(axTop, ...
    [ ...
        n1 + 0.5, ...
        n1 + n2 + 0.5, ...
        n1 + n2 + 0.5, ...
        n1 + 0.5 ...
    ], ...
    [0, 0, 1, 1], ...
    groupColors(2,:), ...
    'EdgeColor', 'none' ...
);


%% =========================================================
% K = 10 block
% =========================================================

patch(axTop, ...
    [ ...
        n1 + n2 + 0.5, ...
        n1 + n2 + n3 + 0.5, ...
        n1 + n2 + n3 + 0.5, ...
        n1 + n2 + 0.5 ...
    ], ...
    [0, 0, 1, 1], ...
    groupColors(3,:), ...
    'EdgeColor', 'none' ...
);


%% =========================================================
% Avg block
% =========================================================

patch(axTop, ...
    [ ...
        n1 + n2 + n3 + 0.5, ...
        nCols + 0.5, ...
        nCols + 0.5, ...
        n1 + n2 + n3 + 0.5 ...
    ], ...
    [0, 0, 1, 1], ...
    groupColors(4,:), ...
    'EdgeColor', 'none' ...
);


%% =========================================================
% Top labels
% =========================================================

text(axTop, ...
    n1/2 + 0.5, ...
    0.5, ...
    'K = 5', ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'middle', ...
    'FontWeight', 'bold', ...
    'FontSize', fontTop, ...
    'Color', 'black' ...
);


text(axTop, ...
    n1 + n2/2 + 0.5, ...
    0.5, ...
    'K = 7', ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'middle', ...
    'FontWeight', 'bold', ...
    'FontSize', fontTop, ...
    'Color', 'black' ...
);


text(axTop, ...
    n1 + n2 + n3/2 + 0.5, ...
    0.5, ...
    'K = 10', ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'middle', ...
    'FontWeight', 'bold', ...
    'FontSize', fontTop, ...
    'Color', 'black' ...
);


text(axTop, ...
    nCols, ...
    0.5, ...
    'Avg', ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'middle', ...
    'FontWeight', 'bold', ...
    'FontSize', fontTopAvg, ...
    'Color', 'black' ...
);


%% =========================================================
% Format top axis
% =========================================================

xlim(axTop, [0.5 nCols + 0.5]);
ylim(axTop, [0 1]);

axTop.XTick = [];
axTop.YTick = [];

axTop.XColor = 'none';
axTop.YColor = 'none';

box(axTop, 'off');

hold(axTop, 'off');